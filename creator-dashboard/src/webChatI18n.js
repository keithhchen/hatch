export class WebChatPresentationError extends Error {
  constructor(key, values = {}) {
    super(key);
    this.name = "WebChatPresentationError";
    this.key = key;
    this.values = values;
  }
}

export function webChatT(locale, key, values = {}) {
  const template = webChatCopy[locale]?.[key] ?? webChatCopy.en[key] ?? key;
  return Object.entries(values).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), template);
}

export function webChatErrorText(error, locale) {
  if (!error) return "";
  if (error.key) return webChatT(locale, error.key, error.values);
  if (error.code && webChatCopy.en[error.code]) return webChatT(locale, error.code, error.values);
  const codeKeys = {
    web_local_tool_unavailable: "browserLocalToolUnavailable",
    browser_approval_unavailable: "browserApprovalUnavailable",
    approval_denied: "approvalDenied"
  };
  if (codeKeys[error.code]) return webChatT(locale, codeKeys[error.code], error.values);
  return error.message ?? String(error);
}
