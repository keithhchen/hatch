export function statusLabel(copy, value) {
  if (value === null || value === undefined || value === "") return "";
  return copy.status?.[value] ?? String(value).replaceAll("_", " ");
}

export function eventLabel(copy, type) {
  return copy.event?.[type] ?? String(type ?? "");
}
