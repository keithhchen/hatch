export const TRANSLATIONS = Object.freeze({ en: EN, "zh-CN": ZH, ja: JA });

const SUPPORTED = new Set(SUPPORTED_LANGUAGES);
const has = (object, key) => Object.prototype.hasOwnProperty.call(object, key);

/** Saved preference or locale → "system" | "en" | "zh-CN" | "ja". */
export function normalizeLanguagePreference(value) {
  if (typeof value !== "string") return SYSTEM_LANGUAGE;
  const normalized = value.trim().replaceAll("_", "-").toLowerCase();
  const primary = normalized.split("-", 1)[0];
  if (primary === "zh") return "zh-CN";
  if (primary === "ja") return "ja";
  if (primary === "en") return "en";
  return SYSTEM_LANGUAGE;
}

/** The first supported OS locale wins when the preference is "system". */
export function resolveLanguage(preference, systemLocales = []) {
  const normalized = normalizeLanguagePreference(preference);
  if (SUPPORTED.has(normalized)) return normalized;
  for (const locale of Array.isArray(systemLocales) ? systemLocales : [systemLocales]) {
    const candidate = normalizeLanguagePreference(locale);
    if (SUPPORTED.has(candidate)) return candidate;
  }
  return DEFAULT_LANGUAGE;
}

export function systemLocales() {
  const languages = globalThis.navigator?.languages;
  return Array.isArray(languages) && languages.length ? languages : [globalThis.navigator?.language ?? DEFAULT_LANGUAGE];
}

/** `t(key, values)`: the language's text, else English, else the key itself. */
export function createTranslator(language, catalogs = TRANSLATIONS) {
  const resolved = SUPPORTED.has(language) ? language : DEFAULT_LANGUAGE;
  const t = (key, values = {}) => {
    const catalog = catalogs[resolved] ?? {};
    const template = has(catalog, key) ? catalog[key] : has(catalogs[DEFAULT_LANGUAGE] ?? {}, key) ? catalogs[DEFAULT_LANGUAGE][key] : key;
    return String(template).replace(/\{([A-Za-z0-9_.-]+)\}/g, (match, name) => has(values, name) ? String(values[name] ?? "") : match);
  };
  Object.defineProperty(t, "language", { value: resolved, enumerable: true });
  return t;
}

/** Localized text for any error the chat or shell can surface. */
export function errorText(t, error) {
  if (!error) return "";
  if (error.key && has(EN, error.key)) return t(error.key, error.values);
  if (error.code && has(EN, error.code)) return t(error.code, error.values);
  return error.message || t("genericError");
}
