/**
 * Normalize a saved language preference or locale-like value. Empty and
 * unsupported values intentionally become `system`, so corrupt local settings
 * cannot strand the UI in an unknown language.
 */
export function normalizeLanguagePreference(value) {
  if (typeof value !== "string") return SYSTEM_LANGUAGE;
  const normalized = value.trim().replaceAll("_", "-").toLowerCase();
  if (!normalized || normalized === SYSTEM_LANGUAGE || normalized === "auto" || normalized === "default") {
    return SYSTEM_LANGUAGE;
  }

  const primaryLanguage = normalized.split("-", 1)[0];
  if (primaryLanguage === "zh") return "zh-CN";
  if (primaryLanguage === "ja") return "ja";
  if (primaryLanguage === "en") return "en";
  return SYSTEM_LANGUAGE;
}

/**
 * Resolve a saved preference against an ordered list of native OS locales.
 * The first supported locale wins; English is the deterministic final fallback.
 */
export function resolveLanguage(preference, systemLocales = []) {
  const normalizedPreference = normalizeLanguagePreference(preference);
  if (SUPPORTED_LANGUAGE_SET.has(normalizedPreference)) return normalizedPreference;

  const candidates = Array.isArray(systemLocales)
    ? systemLocales
    : typeof systemLocales === "string"
      ? [systemLocales]
      : [];

  for (const locale of candidates) {
    const normalizedLocale = normalizeLanguagePreference(locale);
    if (SUPPORTED_LANGUAGE_SET.has(normalizedLocale)) return normalizedLocale;
  }
  return DEFAULT_LANGUAGE;
}

/**
 * Create a translator for a resolved language. The optional catalog argument
 * keeps fallback behavior independently testable without mutating app catalogs.
 */
export function createTranslator(language, catalogs = TRANSLATIONS) {
  const normalized = normalizeLanguagePreference(language);
  const resolvedLanguage = SUPPORTED_LANGUAGE_SET.has(normalized) ? normalized : DEFAULT_LANGUAGE;

  const t = (key, values = {}) => {
    const normalizedKey = String(key ?? "").trim();
    const requestedKeys = pluralKeys(normalizedKey, values);
    const localized = findMessage(catalogs?.[resolvedLanguage], requestedKeys);
    const english = localized === undefined
      ? findMessage(catalogs?.[DEFAULT_LANGUAGE], requestedKeys)
      : localized;
    const template = english === undefined
      ? `[missing:${normalizedKey || "<empty>"}]`
      : String(english);
    return interpolate(template, values);
  };

  Object.defineProperty(t, "language", {
    configurable: false,
    enumerable: true,
    value: resolvedLanguage,
    writable: false
  });
  return t;
}

export function formatDuration(ms, language = DEFAULT_LANGUAGE) {
  const numericMs = Number(ms);
  const totalSeconds = Number.isFinite(numericMs)
    ? Math.max(0, Math.floor(numericMs / 1000))
    : 0;
  const t = createTranslator(language);
  if (totalSeconds < 60) {
    return t("duration.seconds", { seconds: totalSeconds });
  }
  return t("duration.minutesSeconds", {
    minutes: Math.floor(totalSeconds / 60),
    seconds: totalSeconds % 60
  });
}

export function englishMessage(key, values = {}) {
  return createTranslator(DEFAULT_LANGUAGE)(key, values);
}

/**
 * Translate the legacy runtime's English status payloads at the desktop
 * boundary. Unknown status copy is deliberately reduced to a localized
 * generic state instead of leaking server UI prose into the renderer.
 */
export function runtimeAssistantStatusDescriptor(content) {
  const normalized = typeof content === "string" ? content.trim() : "";
  if (HAS_OWN(EN_MESSAGES, normalized) && normalized.startsWith("run.")) {
    return { key: normalized, values: {} };
  }
  if (HAS_OWN(LEGACY_RUNTIME_STATUS_KEYS, normalized)) {
    return { key: LEGACY_RUNTIME_STATUS_KEYS[normalized], values: {} };
  }

  const callingTool = normalized.match(/^Calling tool (.+)\.$/);
  if (callingTool) {
    return { key: "run.status.callingTool", values: { name: callingTool[1] } };
  }
  const finishedTool = normalized.match(/^Tool (.+) (failed|completed)\.$/);
  if (finishedTool) {
    return {
      key: finishedTool[2] === "failed" ? "run.status.toolFailed" : "run.status.toolCompleted",
      values: { name: finishedTool[1] }
    };
  }
  return { key: "run.status.working", values: {} };
}

export function runtimeTurnStatusDescriptor(status) {
  const normalized = typeof status === "string" ? status.trim() : "";
  return {
    key: RUNTIME_TURN_STATUS_KEYS[normalized] ?? "run.status.working",
    values: {}
  };
}

function pluralKeys(key, values) {
  if (values && HAS_OWN(values, "count")) {
    const count = Number(values.count);
    if (Number.isFinite(count)) {
      return [`${key}.${count === 1 ? "one" : "other"}`, key];
    }
  }
  return [key];
}

function findMessage(catalog, keys) {
  if (!catalog || typeof catalog !== "object") return undefined;
  for (const key of keys) {
    if (HAS_OWN(catalog, key)) return catalog[key];
  }
  return undefined;
}

function interpolate(template, values) {
  if (!values || typeof values !== "object") return template;
  return template.replace(/\{([A-Za-z0-9_.-]+)\}/g, (placeholder, name) => {
    if (!HAS_OWN(values, name)) return placeholder;
    return values[name] === null || values[name] === undefined ? "" : String(values[name]);
  });
}
