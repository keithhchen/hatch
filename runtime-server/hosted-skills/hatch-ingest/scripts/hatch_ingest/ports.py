"""Ports: the contracts the application core depends on. Adapters implement these."""
from __future__ import annotations

from pathlib import Path
from typing import Any, Iterable, Protocol, Sequence

from .domain import Converted, Item, ItemResult, PageCapture, Payload, Profile, ProfileState


class Source(Protocol):
    def supports(self, item: Item) -> bool: ...
    def fetch(self, item: Item, workdir: Path) -> Payload: ...


class Browser(Protocol):
    def capture(self, url: str, profile: Profile | None, workdir: Path) -> PageCapture: ...
    def cookies(self) -> dict[str | None, list[dict[str, Any]]]: ...
    def close(self) -> None: ...


class Converter(Protocol):
    name: str

    def matches(self, payload: Payload) -> bool: ...
    def convert(self, payload: Payload, ctx: Any) -> Converted: ...


class Transcriber(Protocol):
    provider: str
    model: str

    @property
    def available(self) -> bool: ...

    def transcribe(self, pcm_s16le_16k_mono: Iterable[bytes]) -> str: ...


class Delivery(Protocol):
    def deliver(self, item: Item, payload: Payload, converted: Converted) -> ItemResult: ...
    def fail(self, item: Item, error: str) -> ItemResult: ...
    def save_cookies(self, profile_id: str, cookies: Sequence[dict[str, Any]]) -> None: ...
    def finish(self, results: Sequence[ItemResult], profiles: Sequence[ProfileState]) -> list[str]: ...
